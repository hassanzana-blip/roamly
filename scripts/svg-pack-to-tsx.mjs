#!/usr/bin/env node
// Generate React glyph components from the official HelloSky SVG pack.
// Source of truth: public/icons/*.svg (docs/reference/hellosky-svg-pack).
// Run: node scripts/svg-pack-to-tsx.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const src = path.resolve("public/icons");
const out = path.resolve("src/components/graphics/pack");
const ATTR = { "stroke-width": "strokeWidth", "stroke-linecap": "strokeLinecap", "stroke-linejoin": "strokeLinejoin", "stroke-dasharray": "strokeDasharray", "stroke-dashoffset": "strokeDashoffset", "stroke-opacity": "strokeOpacity", "fill-opacity": "fillOpacity", "fill-rule": "fillRule", "clip-rule": "clipRule", "stroke-miterlimit": "strokeMiterlimit" };
const COLOR = { "#C4F71D": "hsl(var(--primary))", "#c4f71d": "hsl(var(--primary))", "#9CA3AF": "hsl(var(--muted-foreground))", "#161618": "currentColor" };

const pascal = (s) => s.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const files = readdirSync(src).filter((f) => f.endsWith(".svg") && f !== "sprite.svg").sort();
const exportsOut = [];
let body = `/* Generated by scripts/svg-pack-to-tsx.mjs from public/icons. Do not edit by hand. */\nimport { Glyph, type GlyphProps } from "../Glyph";\n\n`;
for (const f of files) {
  const raw = readFileSync(path.join(src, f), "utf8");
  const title = (raw.match(/<title[^>]*>([^<]*)<\/title>/) ?? [])[1] ?? "";
  let inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title[^>]*>[^<]*<\/title>/, "").trim();
  inner = inner.replace(/(\S+)="([^"]*)"/g, (m, k, v) => {
    const key = ATTR[k] ?? k;
    const val = COLOR[v] ?? v;
    return `${key}="${val}"`;
  });
  inner = inner.replace(/<!--[\s\S]*?-->/g, "");
  const name = "Hs" + pascal(f.replace(/\.svg$/, ""));
  exportsOut.push({ name, file: f, title });
  body += `/** ${title} (${f}) */\nexport function ${name}(p: GlyphProps) {\n  return (\n    <Glyph strokeWidth={1.8} {...p}>\n      ${inner.split("\n").map((l) => l.trim()).filter(Boolean).join("\n      ")}\n    </Glyph>\n  );\n}\n\n`;
}
writeFileSync(path.join(out, "index.tsx"), body);
writeFileSync(path.join(out, "manifest.json"), JSON.stringify(exportsOut, null, 2));
console.log(`generated ${files.length} components`);
